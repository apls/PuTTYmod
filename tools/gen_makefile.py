#!/usr/bin/env python3
"""Generate Makefile.vc (nmake, Visual Studio .NET 2003) for putty.exe."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def listing(d, files=None):
    if files is None:
        files = sorted(f for f in os.listdir(os.path.join(ROOT, d))
                       if f.endswith('.c'))
    return files

root_c = ['be_list.c', 'callback.c', 'cmdline.c', 'config.c', 'errsock.c',
          'ldisc.c', 'logging.c', 'pinger.c', 'settings.c', 'sshpubk.c',
          'sshrand.c', 'timing.c', 'x11disp.c']
stubs_c = ['no-console.c', 'null-cipher.c', 'null-key.c', 'null-lp.c',
           'null-mac.c', 'null-opener.c', 'null-plug.c', 'null-seat.c',
           'null-socket.c']
proxy_c = ['cproxy.c', 'http.c', 'interactor.c', 'local.c', 'newmain.c',
           'proxy.c', 'socks4.c', 'socks5.c', 'sshproxy.c', 'telnet.c']
ssh_c = listing('ssh')
crypto_c = listing('crypto')
utils_c = listing('utils')
term_c = listing('terminal')
wutils_c = listing('windows/utils')
windows_c = ['agent-client.c', 'config.c', 'controls.c', 'dialog.c', 'gss.c',
             'handle-io.c', 'handle-socket.c', 'handle-wait.c', 'help.c',
             'jump-list.c', 'local-proxy.c', 'named-pipe-client.c',
             'named-pipe-server.c', 'network.c', 'noise.c', 'printing.c',
             'putty.c', 'select-gui.c', 'serial.c', 'sharing.c', 'sizetip.c',
             'storage.c', 'unicode.c', 'window.c']

groups = [
    ('.', 'obj', root_c),
    ('generated', 'obj\\generated', ['commit.c']),
    ('utils', 'obj\\utils', utils_c),
    ('stubs', 'obj\\stubs', stubs_c),
    ('crypto', 'obj\\crypto', crypto_c),
    ('proxy', 'obj\\proxy', proxy_c),
    ('ssh', 'obj\\ssh', ssh_c),
    ('terminal', 'obj\\terminal', term_c),
    ('windows', 'obj\\windows', windows_c),
    ('windows\\utils', 'obj\\wutils', wutils_c),
]

objs = []
for src, od, files in groups:
    for f in files:
        objs.append('%s\\%s.obj' % (od, f[:-2]))

lines = []
w = lines.append
w('# Makefile.vc - build putty.exe with Microsoft Visual Studio .NET 2003')
w('#')
w('# Usage (from a "VS .NET 2003 Command Prompt", or after running')
w('# vcvars32.bat):')
w('#')
w('#     nmake -f Makefile.vc          build putty.exe')
w('#     nmake -f Makefile.vc clean    remove build products')
w('#')
w('# Generated by tools/gen_makefile.py; regenerate if source files move.')
w('')
w('CC      = cl')
w('RC      = rc')
w('LINK    = link')
w('')
w('CFLAGS  = /nologo /TP /MT /O1 /Zc:forScope /W3 '
  '/wd4018 /wd4146 /wd4244 /wd4267 /wd4293 /wd4090 /wd4701 /wd4715 '
  '/I. /Icompat /Iterminal /Igenerated /Iwindows '
  '/DWIN32 /D_WINDOWS /D_CRT_SECURE_NO_WARNINGS /DHAVE_CMAKE_H')
w('BELIST_FLAGS = /DAPPNAME=PuTTY /DSSH=1 /DSERIAL=1 /DOTHERBACKENDS=1')
w('')
w('LFLAGS  = /nologo /subsystem:windows')
w('LIBS    = advapi32.lib comdlg32.lib gdi32.lib imm32.lib ole32.lib '
  'shell32.lib user32.lib ws2_32.lib kernel32.lib comctl32.lib')
w('')
w('OBJ = \\')
for i, o in enumerate(objs):
    w('        %s%s' % (o, ' \\' if i != len(objs)-1 else ''))
w('')
w('all: putty.exe')
w('')
w('putty.exe: $(OBJ) putty.res')
w('\t$(LINK) $(LFLAGS) /out:putty.exe $(OBJ) putty.res $(LIBS)')
w('')
w('putty.res: windows\\putty.rc windows\\rcstuff.h windows\\putty-rc.h '
  'windows\\help.rc2 windows\\putty-common.rc2 windows\\version.rc2 '
  'version.h generated\\licence.h generated\\cmake.h')
w('\t$(RC) /nologo /fo putty.res /i. /igenerated /d HAVE_CMAKE_H '
  'windows\\putty.rc')
w('')
w('# be_list.c needs the per-application backend-selection defines.')
w('obj\\be_list.obj: be_list.c')
w('\t$(CC) $(CFLAGS) $(BELIST_FLAGS) /c /Foobj\\be_list.obj be_list.c')
w('')
for src, od, files in groups:
    if src == '.':
        continue
    w('# %s' % src)
    w('{%s\\}.c{%s\\}.obj:' % (src, od))
    w('\t$(CC) $(CFLAGS) /c /Fo%s\\ $<' % od)
    w('')
w('# root directory (except be_list.c, which has its own rule above)')
w('{.\\}.c{obj\\}.obj:')
w('\t$(CC) $(CFLAGS) /c /Foobj\\ $<')
w('')
w('dirs:')
for _, od, _ in groups:
    w('\t@if not exist %s mkdir %s' % (od, od))
w('')
w('clean:')
w('\t-@if exist obj rmdir /s /q obj')
w('\t-@del /q putty.exe putty.res 2>nul')
w('')

open(os.path.join(ROOT, 'Makefile.vc'), 'w', newline='\r\n').write('\n'.join(lines))
print('Makefile.vc written:', len(objs), 'objects')
